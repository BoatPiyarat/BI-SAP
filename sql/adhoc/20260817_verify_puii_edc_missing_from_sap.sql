-- Same "real invoice" definition sql/ddl/005_recon_all_charges.sql uses for sap_invoiced, but at
-- order_item grain (any period) since this sheet carries no period column.
sap_invoiced_any_period AS (
  SELECT DISTINCT U_OrderItem
  FROM `pacific-plating-282708.sap_integration_v3.stg_sap_state`
  WHERE IFNULL(U_InvoiceNo, '') != ''
),

classified AS (
  SELECT
    p.order_item,
    CASE WHEN si.U_OrderItem IS NOT NULL THEN TRUE ELSE FALSE END AS now_in_sap,
    excl.rule_code AS excluded_rule_code,
    val.check_name AS validation_check_name
  FROM puii_reported p
  LEFT JOIN sap_invoiced_any_period si ON si.U_OrderItem = p.order_item
  LEFT JOIN (
    SELECT DISTINCT order_item, rule_code FROM `pacific-plating-282708.sap_integration_v3.sap_excluded_records`
  ) excl ON excl.order_item = p.order_item
  LEFT JOIN (
    SELECT DISTINCT order_item, check_name FROM `pacific-plating-282708.sap_integration_v3.sap_validation_error`
  ) val ON val.order_item = p.order_item
)

SELECT
  CASE
    WHEN now_in_sap THEN 'ALREADY_IN_SAP_NOW'            -- sheet is stale; imported since the sheet was last edited, or its own status was wrong
    WHEN excluded_rule_code IS NOT NULL THEN 'LEGITIMATELY_EXCLUDED'  -- EXCLUDED != DELETED, per rule_code - not a bug
    WHEN validation_check_name IS NOT NULL THEN 'QUARANTINED_VALIDATION_ERROR'  -- known, logged, not a silent drop
    ELSE 'STILL_MISSING_SILENT_DROP'                      -- the real actionable population for the interface file
  END AS classification,
  COUNT(*) AS n
FROM classified
GROUP BY classification
ORDER BY classification;

